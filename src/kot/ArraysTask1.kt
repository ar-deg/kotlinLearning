package kot

/*
 В массив A[N] занесены натуральные числа. Найти сумму тех элементов, которые кратны данному K.
 */
fun main() {
    val n = arrayOf(10, 20, 30, 88, 55, 61, 70, 107)
    val k = 5
    var sum = 0
    for (i in n) {
        if (i % k == 0) {
            sum += i
        }
    }
    println("Сумма элементов, которые кратны 5: $sum")


}